const savedLanguage = localStorage.getItem('matarzat-language') ?? 'ar'

void i18n.use(initReactI18next).init({
  resources: { ar, en },
  lng: savedLanguage,
  fallbackLng: 'ar',
  interpolation: { escapeValue: false },
})

export const applyDocumentLanguage = (language: string) => {
  const normalized = language.startsWith('ar') ? 'ar' : 'en'
  document.documentElement.lang = normalized
  document.documentElement.dir = normalized === 'ar' ? 'rtl' : 'ltr'
  localStorage.setItem('matarzat-language', normalized)
}

applyDocumentLanguage(savedLanguage)
i18n.on('languageChanged', applyDocumentLanguage)

export default i18n
