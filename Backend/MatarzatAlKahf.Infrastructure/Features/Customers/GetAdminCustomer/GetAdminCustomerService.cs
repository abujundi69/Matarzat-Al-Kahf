namespace MatarzatAlKahf.Infrastructure.Features.Customers.Services;
public sealed partial class AdminCustomerService
{
    public async Task<AdminCustomerResponse> GetAsync(Guid id, CancellationToken cancellationToken)
    {
        AdminCustomerResponse? customer = await dbContext.Customers.AsNoTracking().Where(item => item.Id == id && !item.IsDeleted).Select(CustomerProjection).SingleOrDefaultAsync(cancellationToken);
        return customer ?? throw new NotFoundException("Customer was not found.");
    }
}
