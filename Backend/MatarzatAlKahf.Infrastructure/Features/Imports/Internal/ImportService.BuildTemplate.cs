namespace MatarzatAlKahf.Infrastructure.Features.DataImports.Services;
public sealed partial class ImportService
{
    private static ExportFile BuildTemplate(IReadOnlyList<string> headers, string fileName)
    {
        var stream = new MemoryStream();
        using (SpreadsheetDocument document = SpreadsheetDocument.Create(stream, SpreadsheetDocumentType.Workbook, true))
        {
            WorkbookPart workbookPart = document.AddWorkbookPart();
            workbookPart.Workbook = new Workbook();
            WorksheetPart worksheetPart = workbookPart.AddNewPart<WorksheetPart>();
            worksheetPart.Worksheet = new Worksheet(new SheetData(new Row(headers.Select(header => new Cell { DataType = CellValues.InlineString, InlineString = new InlineString(new Text(header)) }))));
            var sheets = workbookPart.Workbook.AppendChild(new Sheets());
            sheets.Append(new Sheet { Id = workbookPart.GetIdOfPart(worksheetPart), SheetId = 1, Name = "Import" });
            workbookPart.Workbook.Save();
        }

        stream.Position = 0;
        return new ExportFile(stream, ExcelContentType, fileName);
    }
}
