using Microsoft.EntityFrameworkCore;

namespace MatarzatAlKahf.Infrastructure.Features.Notifications.Services;
public sealed partial class NotificationService
{
    private async Task<Notification> FindAsync(Guid id, CancellationToken cancellationToken) => await dbContext.Notifications.SingleOrDefaultAsync(item => item.Id == id && !item.IsDeleted, cancellationToken) ?? throw new NotFoundException("Notification was not found.");
}
