namespace MatarzatAlKahf.Infrastructure.Features.Payments.Services;
public sealed partial class PaymentService
{
    private async Task<IReadOnlyList<PaymentResponse>> ListAsync(Guid orderId, bool includeVerification, CancellationToken cancellationToken)
    {
        List<Payment> payments = await dbContext.Payments.AsNoTracking().Where(payment => payment.OrderId == orderId && !payment.IsDeleted).OrderBy(payment => payment.CreatedAtUtc).ToListAsync(cancellationToken);
        return payments.Select(payment => Map(payment, includeVerification)).ToArray();
    }
}
