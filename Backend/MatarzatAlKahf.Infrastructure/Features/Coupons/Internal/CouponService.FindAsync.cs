namespace MatarzatAlKahf.Infrastructure.Features.Coupons.Services;
public sealed partial class CouponService
{
    private async Task<Coupon> FindAsync(Guid id, bool tracked, CancellationToken cancellationToken)
    {
        IQueryable<Coupon> query = Query().Where(coupon => coupon.Id == id && !coupon.IsDeleted);
        if (!tracked)
        {
            query = query.AsNoTracking();
        }

        return await query.SingleOrDefaultAsync(cancellationToken) ?? throw new NotFoundException("Coupon was not found.");
    }
}
